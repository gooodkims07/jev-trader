const DICT: Record<Lang, Record<Key, string>> = { en, ko };
const STORE = "jev.lang";

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface LangCtx { lang: Lang; setLang: (l: Lang) => void; t: T }

const Ctx = createContext<LangCtx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function LangProvider({ fallback, children }: { fallback: Lang; children: ReactNode }) {
  const [chosen, setChosen] = useState<Lang | null>(null);
  useEffect(() => {
    try {
      const s = localStorage.getItem(STORE);
      if (s === "ko" || s === "en") setChosen(s);
    } catch {
      /* storage blocked: follow the server */
    }
  }, []);
  const lang = chosen ?? fallback;
  const setLang = useCallback((l: Lang) => {
    setChosen(l);
    try { localStorage.setItem(STORE, l); } catch { /* not remembered, still switched */ }
  }, []);
  const t = useCallback<T>((key, vars) => {
    let s: string = DICT[lang][key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);

/** A window in seconds, or a row's label ("30s", "1m"), in the viewer's language: 30 -> "30초" / "30s". */
export function span(t: T, v: number | string): string {
  if (v === "from high") return t("spike.fromHigh");
  if (v === "from low") return t("spike.fromLow");
  const sec = typeof v === "number" ? v : v.endsWith("m") ? Number(v.slice(0, -1)) * 60 : Number(v.replace(/s$/, ""));
  if (!Number.isFinite(sec)) return String(v);
  if (sec >= 3600 && sec % 3600 === 0) return t("span.h", { n: sec / 3600 });
  return sec % 60 === 0 ? t("span.m", { n: sec / 60 }) : t("span.s", { n: sec });
}
